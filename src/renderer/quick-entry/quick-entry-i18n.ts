export type QuickEntryCopyKey = keyof typeof copy.en;

export function quickEntryCopy(locale: Locale, key: QuickEntryCopyKey): string {
  const value = copy[locale][key] ?? copy.en[key] ?? key;
  return typeof value === 'string' ? value : key;
}

export function quickEntryOversellCopy(locale: Locale, available: number): string {
  return copy[locale].oversell(available);
}
